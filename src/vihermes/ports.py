"""Ports: implementations are injected, never constructed inside domain services."""

from typing import Protocol

import numpy as np

from .models import Edge, Node


class GraphStore(Protocol):
    def upsert_node(self, node: Node) -> None: ...
    def upsert_edge(self, edge: Edge) -> None: ...
    def get(self, node_id: str) -> Node | None: ...
    def nodes(self) -> list[Node]: ...
    def edges(self, node_id: str, incoming: bool = False) -> list[Edge]: ...
    def close(self) -> None: ...


class Embedder(Protocol):
    @property
    def identity(self) -> str: ...
    def encode(self, texts: list[str]) -> np.ndarray: ...


class LanguageModel(Protocol):
    def json(self, system: str, payload: dict) -> dict: ...


class DenseSearch(Protocol):
    def scores(self, query: str, ids: list[str]) -> np.ndarray: ...
